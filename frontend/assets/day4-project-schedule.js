  function createCalendar(startDate, endDate, skippedSlots) {
    const calendar = [];
    let projectDay = 0;
    for (const cursor = new Date(`${startDate}T00:00:00Z`), end = new Date(`${endDate}T00:00:00Z`); cursor <= end; cursor.setUTCDate(cursor.getUTCDate() + 1)) {
      const isoDate = cursor.toISOString().slice(0, 10);
      const weekDay = cursor.getUTCDay();
      if (weekDay === 0 || weekDay === 6 || projectHolidays.has(isoDate)) continue;
      const periods = ['AM', 'PM'].filter((period) => !skippedSlots.has(`${isoDate}-${period}`));
      if (!periods.length) continue;
      projectDay += 1;
      periods.forEach((period) => calendar.push({
        projectDay,
        period: period === 'AM' ? '오전' : '오후',
        time: period === 'AM' ? '0–4시간' : '4–8시간',
        date: `${cursor.getUTCFullYear()}. ${cursor.getUTCMonth() + 1}. ${cursor.getUTCDate()}.(${dayNames[weekDay]})`
      }));
    }
    return calendar;
  }

